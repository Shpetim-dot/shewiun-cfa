-- Initial PostgreSQL schema for Shewiun CFA.
-- Apply to a dedicated database before setting DATABASE_URL/CFA_DATABASE_URL.
-- Keep schema changes in version control; do not point this at unrelated production data.

CREATE TABLE IF NOT EXISTS projects (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'Active', created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS brain (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, content TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'Fact', source TEXT NOT NULL DEFAULT 'User input',
  confidence INTEGER NOT NULL DEFAULT 80, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS council (
  id TEXT PRIMARY KEY, topic TEXT NOT NULL, result TEXT NOT NULL,
  transcript TEXT NOT NULL, mode TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS activity (
  id TEXT PRIMARY KEY, action TEXT NOT NULL, detail TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS audit_events (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id TEXT UNIQUE NOT NULL,
  event_type TEXT NOT NULL, actor TEXT NOT NULL, payload TEXT NOT NULL,
  previous_hash TEXT NOT NULL, event_hash TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS approval_requests (
  id TEXT PRIMARY KEY, action_type TEXT NOT NULL, description TEXT NOT NULL,
  requested_by TEXT NOT NULL, risk_level TEXT NOT NULL, status TEXT NOT NULL,
  decision_by TEXT, decision_note TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, decided_at TEXT
);
CREATE TABLE IF NOT EXISTS runtime_runs (
  id TEXT PRIMARY KEY, kind TEXT NOT NULL, status TEXT NOT NULL, input_json TEXT NOT NULL,
  state_json TEXT NOT NULL, result_json TEXT, error TEXT, attempt INTEGER NOT NULL DEFAULT 0,
  max_attempts INTEGER NOT NULL DEFAULT 3, created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
  started_at TEXT, finished_at TEXT, cancel_requested INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_runtime_runs_status_created ON runtime_runs(status, created_at);
CREATE TABLE IF NOT EXISTS runtime_events (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, run_id TEXT NOT NULL,
  event_type TEXT NOT NULL, payload_json TEXT NOT NULL, created_at TEXT NOT NULL,
  FOREIGN KEY(run_id) REFERENCES runtime_runs(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS review_submissions (
  id TEXT PRIMARY KEY, playbook_version TEXT NOT NULL, answers_json TEXT NOT NULL,
  status TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS review_results (
  id TEXT PRIMARY KEY, submission_id TEXT NOT NULL UNIQUE, share_token TEXT NOT NULL UNIQUE,
  result_json TEXT NOT NULL, model_configured INTEGER NOT NULL, created_at TEXT NOT NULL,
  FOREIGN KEY(submission_id) REFERENCES review_submissions(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS review_leads (
  id TEXT PRIMARY KEY, submission_id TEXT NOT NULL, email TEXT NOT NULL,
  consent INTEGER NOT NULL, created_at TEXT NOT NULL,
  FOREIGN KEY(submission_id) REFERENCES review_submissions(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS review_test_requests (
  id TEXT PRIMARY KEY, submission_id TEXT NOT NULL, request_json TEXT NOT NULL,
  created_at TEXT NOT NULL,
  FOREIGN KEY(submission_id) REFERENCES review_submissions(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS review_rate_limits (
  bucket TEXT NOT NULL, subject_hash TEXT NOT NULL, count INTEGER NOT NULL,
  window_started_at TEXT NOT NULL, PRIMARY KEY(bucket, subject_hash)
);
CREATE TABLE IF NOT EXISTS review_analytics (
  id TEXT PRIMARY KEY, submission_id TEXT, event_name TEXT NOT NULL,
  metadata_json TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_review_submissions_created ON review_submissions(created_at);
CREATE INDEX IF NOT EXISTS idx_review_analytics_created ON review_analytics(created_at);

CREATE TABLE IF NOT EXISTS api_rate_limits (
  bucket_key TEXT PRIMARY KEY, window_started_at DOUBLE PRECISION NOT NULL, count INTEGER NOT NULL
);
